SP = lambda h: b('spacer', h=h)                      # noqa: E731


def TABLE(head, rows, widths, small=False):
    return b('table', head=head, rows=rows, widths=widths, small=small)


def PIC(name, w, h):
    return b('pic', name=name, w=w, h=h)


def CHART(name):
    return b('chart', name=name)


